package com.attendance;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import jakarta.annotation.PostConstruct;
import java.time.*;
import java.util.*;

@Service
public class AttendanceService {
    final JdbcTemplate db;
    final ObjectMapper json;
    static final ZoneId ZONE = ZoneId.of("Asia/Shanghai");
    @Value("${attendance.seed-demo}") boolean seedDemo;
    public AttendanceService(JdbcTemplate db, ObjectMapper json) { this.db = db; this.json = json; }
    @PostConstruct void init() {
        db.execute("CREATE TABLE IF NOT EXISTS employees (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code VARCHAR(30) UNIQUE NOT NULL, name VARCHAR(50) NOT NULL, department VARCHAR(50) NOT NULL, position VARCHAR(80), descriptor CLOB, active BOOLEAN DEFAULT TRUE, demo BOOLEAN DEFAULT FALSE)");
        db.execute("CREATE TABLE IF NOT EXISTS attendance (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, employee_id BIGINT REFERENCES employees(id), attendance_date DATE NOT NULL, check_in TIME, check_out TIME, status VARCHAR(30), source VARCHAR(30), distance DOUBLE, resolved BOOLEAN DEFAULT FALSE, note VARCHAR(300), UNIQUE(employee_id, attendance_date))");
        db.execute("CREATE TABLE IF NOT EXISTS settings (id INT PRIMARY KEY, start_time VARCHAR(5), end_time VARCHAR(5), threshold DOUBLE)");
        db.update("MERGE INTO settings KEY(id) SELECT 1, '09:00', '18:00', 0.50 WHERE NOT EXISTS(SELECT 1 FROM settings WHERE id=1)");
        if (seedDemo && db.queryForObject("SELECT COUNT(*) FROM employees", Integer.class) == 0) seed();
    }
    void seed() {
        String[] names = {"陈思远", "林沐晴", "张明轩", "李若溪", "王一帆", "赵可欣", "周宇航", "刘诗涵", "吴嘉宁", "郑子墨", "许知夏", "孙浩然", "唐雨桐", "何景行", "沈以安", "陆星辰", "宋予安", "顾清和", "方亦舟", "程晓月", "江知行", "夏晚晴", "白书言", "徐望舒"};
        String[] departments = {"产品设计部", "技术研发部", "市场运营部", "人力资源部"};
        for(int i=0;i<names.length;i++) db.update("INSERT INTO employees(code,name,department,position,demo) VALUES(?,?,?,?,TRUE)", "ZQ" + (1001+i), names[i], departments[i%4], i%4==0 ? "产品设计师" : i%4==1 ? "开发工程师" : i%4==2 ? "运营专员" : "人事专员");
        var random = new Random(42);
        LocalDate today = LocalDate.now(ZONE);
        for(int d=30;d>=0;d--) {
            LocalDate day=today.minusDays(d);
            if (day.getDayOfWeek().getValue()>5 && d!=0) continue;
            for(int i=1;i<=24;i++) {
                if(random.nextInt(100)<9) continue;
                boolean late=random.nextInt(100)<12;
                String in=late ? "09:"+String.format("%02d", 1+random.nextInt(28)) : "08:"+String.format("%02d",30+random.nextInt(30));
                db.update("INSERT INTO attendance(employee_id,attendance_date,check_in,check_out,status,source) VALUES(?,?,?,?,?,?)", i, day, in, d==0 ? null : "18:"+String.format("%02d",random.nextInt(40)), late?"迟到":"正常", "演示数据");
            }
        }
    }
    public List<Map<String,Object>> employees() {
        return db.queryForList("SELECT id,code,name,department,position,active,demo,CASE WHEN descriptor IS NULL THEN FALSE ELSE TRUE END AS enrolled FROM employees ORDER BY id").stream().map(this::lower).toList();
    }
    Map<String,Object> lower(Map<String,Object> row) { var out=new LinkedHashMap<String,Object>(); row.forEach((k,v)->out.put(k.toLowerCase(Locale.ROOT), v)); return out; }
    public Map<String,Object> settings() { return lower(db.queryForMap("SELECT * FROM settings WHERE id=1")); }
    @Transactional public void saveSettings(Map<String,Object> input) {
        String start=text(input,"start_time",5), end=text(input,"end_time",5);
        if(!LocalTime.parse(start).isBefore(LocalTime.parse(end))) throw new IllegalArgumentException("下班时间必须晚于上班时间");
        double threshold=((Number)input.get("threshold")).doubleValue();
        if(!Double.isFinite(threshold)||threshold<0.3||threshold>0.6) throw new IllegalArgumentException("识别距离阈值应在 0.30–0.60 之间");
        db.update("UPDATE settings SET start_time=?,end_time=?,threshold=? WHERE id=1",start,end,threshold);
    }
    static String text(Map<String,Object> data,String key,int max) {
        String value=Objects.toString(data.get(key), "").trim();
        if(value.isEmpty()||value.length()>max) throw new IllegalArgumentException("请填写有效的 " + key + "（最多 " + max + " 字）");
        return value;
    }
    @Transactional public void addEmployee(Map<String,Object> data) {
        db.update("INSERT INTO employees(code,name,department,position) VALUES(?,?,?,?)",text(data,"code",30),text(data,"name",50),text(data,"department",50),text(data,"position",80));
    }
    @Transactional public void toggleEmployee(long id,boolean active) {
        if(db.update("UPDATE employees SET active=? WHERE id=?",active,id)==0) throw new IllegalArgumentException("人员不存在");
    }
    static double[] vector(List<Double> list) {
        if(list==null||list.size()!=128) throw new IllegalArgumentException("无效的人脸特征，请重新采集");
        double[] v=new double[128]; double norm=0;
        for(int i=0;i<128;i++) { Double x=list.get(i); if(x==null||!Double.isFinite(x)||Math.abs(x)>2) throw new IllegalArgumentException("无效人脸特征"); v[i]=x;norm+=x*x; }
        if(norm<0.01) throw new IllegalArgumentException("无效人脸特征");
        return v;
    }
    double distance(double[] a,double[] b) { double sum=0; for(int i=0;i<128;i++) sum+=Math.pow(a[i]-b[i],2); return Math.sqrt(sum); }
    double[] decode(String value) { try { return vector(json.readValue(value,new TypeReference<List<Double>>(){})); } catch(Exception e) { throw new IllegalStateException("人脸特征数据损坏"); } }
    @Transactional public synchronized void enroll(long id,List<Double> descriptor) throws Exception {
        double[] v=vector(descriptor);
        for(var row:db.queryForList("SELECT id,CAST(descriptor AS VARCHAR) AS descriptor FROM employees WHERE descriptor IS NOT NULL AND id<>?",id)) {
            if(distance(v,decode(row.get("DESCRIPTOR").toString()))<0.5) throw new IllegalArgumentException("此人脸已被其他人员录入");
        }
        if(db.update("UPDATE employees SET descriptor=? WHERE id=? AND active=TRUE",json.writeValueAsString(descriptor),id)==0) throw new IllegalArgumentException("人员不存在或已停用");
    }
    @Transactional public synchronized Map<String,Object> recognize(List<Double> descriptor,String action) {
        if(!Set.of("in","out").contains(action)) throw new IllegalArgumentException("无效打卡类型");
        double[] v=vector(descriptor); double best=10,second=10; Map<String,Object> match=null;
        for(var row:db.queryForList("SELECT id,name,CAST(descriptor AS VARCHAR) AS descriptor FROM employees WHERE active=TRUE AND descriptor IS NOT NULL")) {
            double d=distance(v,decode(row.get("DESCRIPTOR").toString()));
            if(d<best) { second=best;best=d;match=row; } else if(d<second) second=d;
        }
        if(match==null||best>((Number)settings().get("threshold")).doubleValue()||second-best<0.05) throw new IllegalArgumentException("未找到可靠匹配，请靠近摄像头或先录入人脸");
        var now=LocalDateTime.now(ZONE); var day=now.toLocalDate(); long id=((Number)match.get("ID")).longValue();
        var existing=db.queryForList("SELECT * FROM attendance WHERE employee_id=? AND attendance_date=? FOR UPDATE",id,day);
        if(action.equals("in")) {
            if(!existing.isEmpty()) throw new IllegalArgumentException("今日已签到，请勿重复打卡");
            String status=now.toLocalTime().isAfter(LocalTime.parse(settings().get("start_time").toString()))?"迟到":"正常";
            db.update("INSERT INTO attendance(employee_id,attendance_date,check_in,status,source,distance) VALUES(?,?,?,?,?,?)",id,day,now.toLocalTime(),status,"人脸识别",best);
        } else {
            if(existing.isEmpty()) throw new IllegalArgumentException("请先完成上班签到");
            if(existing.get(0).get("CHECK_OUT")!=null) throw new IllegalArgumentException("今日已签退");
            String status=existing.get(0).get("STATUS").toString();
            if(now.toLocalTime().isBefore(LocalTime.parse(settings().get("end_time").toString()))) status=status.equals("迟到")?"迟到 / 早退":"早退";
            db.update("UPDATE attendance SET check_out=?,status=? WHERE employee_id=? AND attendance_date=?",now.toLocalTime(),status,id,day);
        }
        return Map.of("name",match.get("NAME"),"distance",best,"message",action.equals("in")?"签到成功":"签退成功","time",now.toLocalTime().withNano(0).toString());
    }
    public List<Map<String,Object>> records(LocalDate from,LocalDate to) {
        if(from.isAfter(to)||from.plusDays(366).isBefore(to)) throw new IllegalArgumentException("请选择不超过一年的有效时间范围");
        return db.query("SELECT a.*,e.name,e.code,e.department FROM attendance a JOIN employees e ON e.id=a.employee_id WHERE a.attendance_date BETWEEN ? AND ? ORDER BY a.attendance_date DESC,a.check_in DESC", (rs,n)-> {
            Map<String,Object> r=new LinkedHashMap<>();
            for(String key:List.of("id","employee_id","name","code","department","status","source","resolved","note")) r.put(key,rs.getObject(key));
            r.put("day",rs.getDate("attendance_date").toString());
            r.put("check_in",rs.getTime("check_in")==null?null:rs.getTime("check_in").toString());
            r.put("check_out",rs.getTime("check_out")==null?null:rs.getTime("check_out").toString());
            return r;
        },from,to);
    }
    @Transactional public void resolve(long id,String note) {
        if(note==null||note.isBlank()||note.length()>300) throw new IllegalArgumentException("请填写处理说明（1–300 字）");
        if(db.update("UPDATE attendance SET resolved=TRUE,note=? WHERE id=? AND status<>'正常' AND resolved=FALSE",note,id)==0) throw new IllegalArgumentException("记录不存在、已处理或无需处理");
    }
}
